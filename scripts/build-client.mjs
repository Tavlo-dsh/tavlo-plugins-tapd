import { build, transform } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const read = (path) => readFile(resolve(root, path), 'utf8')
const client = await read('client.js')
const marker = "require('./ui/arcs')"
if (client.split(marker).length !== 2) throw new Error('Expected one Arc adapter require in the DSH client factory')

// Keep identifiable, package-scoped CSS module selectors. Minify the JavaScript
// identifiers separately after CSS module names have become string literals.
const arc = await build({
  absWorkingDir: root,
  entryPoints: ['ui/arcs.tsx'],
  outdir: 'lib',
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  jsx: 'automatic',
  external: ['react', 'react-dom'],
  define: { 'process.env.NODE_ENV': '"production"' },
  plugins: [{
    name: 'bundle-motion-prop-validator',
    setup(esbuild) {
      // Motion deliberately hides this optional lookup from bundlers. Resolve
      // it at build time instead of invoking the DSH loader for an npm module.
      esbuild.onLoad({ filter: /[/\\]filter-props\.mjs$/ }, async ({ path }) => {
        const source = await readFile(path, 'utf8')
        if (!source.includes('loadExternalIsValidProp(require(emotionPkg).default);')) return
        return {
          contents: `import isPropValid from '@emotion/is-prop-valid';\n${source.replace(
            'loadExternalIsValidProp(require(emotionPkg).default);', 'loadExternalIsValidProp(isPropValid);',
          )}`,
        }
      })
    },
  }],
  metafile: true,
  write: false,
  minifySyntax: true,
  minifyWhitespace: true,
  legalComments: 'inline',
})
const js = arc.outputFiles.find(({ path }) => path.endsWith('.js'))
const css = arc.outputFiles.find(({ path }) => path.endsWith('.css'))
if (!js || !css || arc.outputFiles.length !== 2) throw new Error('Expected only bundled Arc JavaScript and CSS')

// Do not let an upstream dependency introduce unsupported runtime requires or
// a separate CSS asset. These React modules are provided by the DSH loader.
const runtimeModules = new Set(['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'])
for (const output of Object.values(arc.metafile.outputs)) {
  for (const entry of output.imports) {
    if (entry.external && !runtimeModules.has(entry.path)) throw new Error(`Unsupported client import: ${entry.path}`)
  }
}
const adapter = await transform(`(() => {
  const module = { exports: {} };
  const __TAVLO_TAPD_ARC_CSS__ = ${JSON.stringify(css.text)};
  ${js.text}
  return module.exports;
})()`, { minify: true, target: 'es2020', legalComments: 'inline' })
for (const [, , importName] of adapter.code.matchAll(/\brequire\((['"])([^'"]+)\1\)/g)) {
  if (!runtimeModules.has(importName)) throw new Error(`Unsupported client require: ${importName}`)
}
const bundled = client.replace(marker, () => adapter.code.trim().replace(/;$/, ''))

// Read the full notice of each package esbuild included in the browser build.
const packageDirs = new Set(Object.keys(arc.metafile.inputs).flatMap((file) => {
  const match = file.match(/^(.*node_modules\/((?:@[^/]+\/)?[^/]+))\//)
  return match ? [match[1]] : []
}))
const notices = [await read('licenses/uiarc-MIT.txt')]
for (const dir of [...packageDirs].sort()) {
  const { name, version } = JSON.parse(await read(`${dir}/package.json`))
  let notice
  for (const file of ['LICENSE', 'LICENSE.txt', 'LICENSE.md', 'LICENSE-MIT', 'license']) {
    try {
      notice = await read(`${dir}/${file}`)
      break
    } catch (error) {
      if (error.code !== 'ENOENT') throw error
    }
  }
  // npm's 2.3.8 archive omits this package's upstream MIT license.
  if (!notice && name === 'react-remove-scroll-bar' && version === '2.3.8') {
    notice = await read('licenses/uiarc-react-remove-scroll-bar-MIT.txt')
  }
  if (!notice) throw new Error(`Missing license: ${name}@${version}`)
  notices.push(`${name}@${version}\n${notice}`)
}

await mkdir(resolve(root, 'lib'), { recursive: true })
await writeFile(resolve(root, 'lib/client.js'), `// Generated by scripts/build-client.mjs. See client.js.LEGAL.txt for third-party notices.\n${bundled}`)
await writeFile(resolve(root, 'lib/client.js.LEGAL.txt'), notices.join('\n\n'))
